import { motion } from 'motion/react'

export function spotlight(e) {
  const r = e.currentTarget.getBoundingClientRect()
  e.currentTarget.style.setProperty('--mx', `${e.clientX - r.left}px`)
  e.currentTarget.style.setProperty('--my', `${e.clientY - r.top}px`)
}

export function Reveal({ children, delay = 0, y = 24, className = '' }) {
  return (
    <motion.div
      className={className}
      initial={{ opacity: 0, y, filter: 'blur(6px)' }}
      whileInView={{ opacity: 1, y: 0, filter: 'blur(0px)' }}
      viewport={{ once: true, margin: '-80px' }}
      transition={{ duration: 0.7, delay, ease: [0.22, 1, 0.36, 1] }}
    >
      {children}
    </motion.div>
  )
}

export function Section({ id, eyebrow, title, children, className = '' }) {
  return (
    <section id={id} className={`relative mx-auto max-w-6xl px-5 py-24 sm:px-8 md:py-32 ${className}`}>
      <Reveal>
        <p className="mb-3 font-mono text-xs uppercase tracking-[0.25em] text-cyan-500 dark:text-cyan-300">{eyebrow}</p>
        <h2 className="mb-12 max-w-3xl text-3xl font-bold tracking-tight sm:text-5xl">{title}</h2>
      </Reveal>
      {children}
    </section>
  )
}

export function Chip({ children, active, onClick }) {
  const cls = `rounded-full border px-3 py-1 font-mono text-xs transition ${
    active
      ? 'border-transparent bg-[var(--fg)] text-[var(--bg)]'
      : 'border-line text-muted hover:text-[var(--fg)] hover:border-[var(--muted)]'
  }`
  return onClick ? (
    <button className={cls} onClick={onClick}>
      {children}
    </button>
  ) : (
    <span className={cls}>{children}</span>
  )
}

